"""图内部模型的结构化输出结构。"""
from typing import Literal, List

from pydantic import BaseModel, Field


class GateOutput(BaseModel):
    """gate 节点的结构化输出，直接写回 State.type。"""

    # 0:违规对话 1:纯对话 2:需要执行任务
    type: Literal[0, 1, 2] = Field(
        description=(
            "本轮用户意图分类，只能取整数 0 / 1 / 2 三者之一，直接写入 State.type。\n"
            "【0 = 违规对话】用户消息命中违法违规、安全风险或明显越界的内容。"
            "这一轮会直接返回固定拒绝回复，不召回用户画像、不召回会话历史、不调用任何工具。\n"
            "【1 = 纯对话】不需要查询或修改任何数据，只是闲聊、情绪表达、问候、"
            "让 AI 谈观点、解释常识或给建议。典型：『今天上班好累』『讲个笑话』"
            "『你觉得我是不是想太多』。注意：判 1 仍然要走用户级记忆注入和本会话回忆，"
            "只是不调用工具。\n"
            "【2 = 需要执行任务】需要动用能力：查询或修改数据、调用组件或工具、"
            "读写日程 / 待办 / 账单 / 健康 / 用户资料等。典型：『查一下我这个月的支出』"
            "『把明天体检记下来』『下周有空吗』『帮我改下昵称』。\n"
            "【判据】看『要不要动用能力（工具 / 组件 / 数据）』，不是看句子像不像命令，"
            "也不是看句子长短或是不是疑问句。\n"
            "【易错边界】\n"
            "- 疑问句常常是 2：『我这个月是不是超支了』『下周有空吗』都必须先查数据才能回答，判 2。\n"
            "- 陈述句也可能是 1：『今天心情不太好』『这周好忙』不查不改任何数据，判 1。\n"
            "- 代词或省略指代按 2：『那餐饮具体哪几笔』『换成下周三呢』承接上一轮任务，判 2。\n"
            "- 混合句按 2：『帮我记下明天体检，顺便说说注意啥』只要含一个要动用能力的诉求就判 2。\n"
            "- 必须结合最近几轮对话判断，只看最后一句会把追问误判成闲聊。\n"
            "- 实在拿不准时输出 2：宁可多走一次任务规划，也不要把该查数据的判成闲聊。\n"
            "【输出】只给这一个整数，不要解释、不要复述理由、不要输出额外字段或额外文字。"
        )
    )

class PlannerOutput(BaseModel):
    """任务计划节点结构化输出"""

    task_list: List[str] = Field(
        description=(
            "本轮规划后该会话的【完整任务清单】，一项任务一个字符串，整表覆盖写入 State.task_list；"
            "不是本轮新增的增量列表，也不是要执行的动作流水。每个字符串对应 agent_task 表里一行的 goal。\n"
            "【每条怎么写】一句完整、脱离上下文也看得懂的简体中文，动词开头，补全对象、时间、数量、条件；"
            "代词与省略指代（『那笔』『换成下周三』『也加一个』）必须结合最近几轮对话还原成具体对象。"
            "不要编号、不要 Markdown、不要『任务1：』这类前缀，不要带解释、理由、状态或结果。\n"
            "【粒度】一条 = 一个能独立执行、能独立判定完成或失败的最小动作；"
            "不要把『查数据 → 计算 → 写库 → 回复』拆成多条，也不要把两个不相关诉求塞进一条。\n"
            "【顺序】按执行先后排列，有依赖的放前面。\n"
            "【数量】只写真正需要动用能力（查询、修改、记录、提醒）的事项；不需要执行任何动作时返回空列表 []。"
            "不要为了显得有规划而硬拆步骤，不要写『理解用户意图』『整理信息』『生成回复』这类内部步骤。\n"
            "【改任务与追加任务】结合输入里的当前任务清单：用户要改某条 → 在对应位置直接重写那条的 goal 文本，"
            "不另起一条、不保留旧值、不写变更记录；要追加 → 在末尾新增一条；未提及的已有任务原样带出，不要漏、不要改写。"
            "表里没有版本、状态、结果，这些一律不输出。\n"
            "【边界】本节点只做规划：不调用工具、不查询数据、不替用户做决定、不编造事实；"
            "需要读外部数据才能确认的事，写成一条任务交给执行层。\n"
            "【输出】只给这个字符串数组，不要额外字段、不要包裹对象、不要输出解释文字。"
        )
    )