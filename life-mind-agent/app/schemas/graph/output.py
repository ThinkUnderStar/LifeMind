"""图内部模型的结构化输出结构。"""
from typing import Literal

from pydantic import BaseModel, Field


class GateOutput(BaseModel):
    """gate 节点的结构化输出，直接写回 State.type。"""

    # 0:违规对话 1:纯对话 2:需要执行任务
    type: Literal[0, 1, 2] = Field(
        description=(
            "本轮用户意图分类，只能取整数 0 / 1 / 2 三者之一，直接写入 State.type。\n"
            "【0 = 违规对话】用户消息命中违法违规、安全风险或明显越界的内容。"
            "这一轮会直接返回固定拒绝回复，不召回用户画像、不召回会话历史、不调用任何工具。\n"
            "【1 = 纯对话】不需要查询或修改任何数据，只是闲聊、情绪表达、问候、"
            "让 AI 谈观点、解释常识或给建议。典型：『今天上班好累』『讲个笑话』"
            "『你觉得我是不是想太多』。注意：判 1 仍然要走用户级记忆注入和本会话回忆，"
            "只是不调用工具。\n"
            "【2 = 需要执行任务】需要动用能力：查询或修改数据、调用组件或工具、"
            "读写日程 / 待办 / 账单 / 健康 / 用户资料等。典型：『查一下我这个月的支出』"
            "『把明天体检记下来』『下周有空吗』『帮我改下昵称』。\n"
            "【判据】看『要不要动用能力（工具 / 组件 / 数据）』，不是看句子像不像命令，"
            "也不是看句子长短或是不是疑问句。\n"
            "【易错边界】\n"
            "- 疑问句常常是 2：『我这个月是不是超支了』『下周有空吗』都必须先查数据才能回答，判 2。\n"
            "- 陈述句也可能是 1：『今天心情不太好』『这周好忙』不查不改任何数据，判 1。\n"
            "- 代词或省略指代按 2：『那餐饮具体哪几笔』『换成下周三呢』承接上一轮任务，判 2。\n"
            "- 混合句按 2：『帮我记下明天体检，顺便说说注意啥』只要含一个要动用能力的诉求就判 2。\n"
            "- 必须结合最近几轮对话判断，只看最后一句会把追问误判成闲聊。\n"
            "- 实在拿不准时输出 2：宁可多走一次任务规划，也不要把该查数据的判成闲聊。\n"
            "【输出】只给这一个整数，不要解释、不要复述理由、不要输出额外字段或额外文字。"
        )
    )
