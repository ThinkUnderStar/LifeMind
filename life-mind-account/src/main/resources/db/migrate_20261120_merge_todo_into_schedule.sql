-- ============================================================================
-- 迁移：把「待办」并入「日程」插件
--
-- 目标库：life_mind_account
-- 执行时机：一次性，随本次发布执行；脚本幂等，可重复执行
-- ============================================================================
--
-- 问题背景
-- --------
-- plugin 表预置了 todo / schedule / bill / health 四行，但 agent 侧
-- SERVICE_TOOLS 只有 schedule 一组工具，待办只是 schedule_create_item 的
-- item_type=todo 分支——同表、同工具、同代码路径。
--
-- 于是 todo 这行成了死开关，并把系统推到最坏状态：
--   1. todo.default_enabled=1，新用户网关注入的插件集合是 "todo"；
--   2. agent 按 plugin_key 取工具，取不到 todo 这一组，一个服务工具都绑不上；
--   3. 唯一有实现的 schedule 反而 default_enabled=0。
-- 净效果：新用户开箱没有任何日程/待办能力，而界面上「待办」还亮着绿灯。
-- 用户主动关掉「日程」、打开「待办」（最符合直觉的操作：只想记待办），
-- 得到的同样是零工具——待办被锁在「日程」这个开关后面。
--
-- 修法
-- ----
-- 承认实现事实：待办与日程同一个插件。删掉 todo 行，把「待办默认开」的
-- 产品意图搬到 schedule 行上，展示名改为「日程与待办」。
--
-- 为什么不给 todo 补一组 todo_* 工具
-- ----------------------------------
-- 两组工具查同一张表，只差一个 item_type 过滤，模型分不清
-- 「明天下午三点开会」算日程还是待办，选错工具的概率会明显上升。
-- 插件粒度跟数据模型走，不跟界面格子走。
-- ============================================================================

USE `life_mind_account`;

-- ----------------------------------------------------------------------------
-- 1. 删除指向 todo 的用户配置
--
-- user_plugin 对 plugin 有外键且 ON DELETE CASCADE，第 2 步删行时会自动带走。
-- 这里仍显式删一次：不依赖外键行为，也让「删了多少用户配置」可见。
--
-- 这些行丢弃是安全的：todo 从来没有对应工具，用户点它的开关不产生任何效果，
-- 不存在需要保留的意图。让合并后的 schedule 走默认值即可。
-- ----------------------------------------------------------------------------
DELETE up FROM `user_plugin` up
JOIN `plugin` p ON p.id = up.plugin_id
WHERE p.plugin_key = 'todo';

-- ----------------------------------------------------------------------------
-- 2. 删除 todo 插件行
-- ----------------------------------------------------------------------------
DELETE FROM `plugin` WHERE `plugin_key` = 'todo';

-- ----------------------------------------------------------------------------
-- 3. 把「待办默认开」的意图搬到 schedule 上
--
-- 这一步会覆盖运营可能在库里改过的 name / description / default_enabled / sort。
-- 是有意为之：本次改动本身就是产品语义变更，旧的展示名「日程」已经
-- 表达不了「待办也在里面」，必须一起改。
-- ----------------------------------------------------------------------------
UPDATE `plugin`
SET `name`            = '日程与待办',
    `description`     = '管理日程、待办与提醒',
    `default_enabled` = 1,
    `sort`            = 10
WHERE `plugin_key` = 'schedule';

-- ----------------------------------------------------------------------------
-- 4. 校验：应恰好剩下 schedule / bill / health 三行，且 schedule 默认开
-- ----------------------------------------------------------------------------
SELECT `plugin_key`, `name`, `status`, `default_enabled`, `sort`
FROM `plugin`
ORDER BY `sort`;

-- ----------------------------------------------------------------------------
-- 5. 必须手动清 Redis 缓存（脚本做不到，需在应用侧执行）
--
-- account 服务把用户启用的插件集合缓存在 life-mind:{userId}:plugins，
-- TTL 7 天，改库不会让它失效。不清的话，老用户 7 天内拿到的仍是 "todo"，
-- 现象和「没修好」完全一样。
--
--   redis-cli --scan --pattern 'life-mind:*:plugins' | xargs -r redis-cli DEL
--
-- 更稳的做法是在 account 服务里提供一个运维接口按 userId 清，
-- 已经存在的是 setPluginEnabled 内部删 key 的逻辑，暂不额外暴露。
-- ----------------------------------------------------------------------------
